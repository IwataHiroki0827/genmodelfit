def t(key: str, lang: str) -> str:
    return T[key][0 if lang == "en" else 1]


def cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def code(text: str) -> str:
    return "`" + str(text).replace("`", "'").replace("|", "\\|") + "`"


# --- 公式の名前を行に割り当てる --------------------------------------------------------------------------


def first(rules: tuple[Rule, ...], text: str) -> Rule | None:
    low = hardware._low(text)
    for r in rules:
        if re.search(r.key, low):
            return r
    return None


def assign(official: dict) -> dict[int, list[str]]:
    """id(行) → 当たる公式の名前(重ねない・並びはそのまま)。"""
    hits: dict[int, list[str]] = {}

    def add(r: Rule | None, name: str) -> None:
        if r is not None and name not in hits.setdefault(id(r), []):
            hits[id(r)].append(name)

    for row in official.get("rocm_hw_specs", []):
        if row.get("graphics_model"):
            add(first(gputables.AMD_NAME_RULES, "AMD " + row["graphics_model"]), row["graphics_model"])
            add(first(gputables.AMD_CPU_IGPU_RULES, "AMD " + row["name"]), row["name"])
        else:
            prefix = "AMD Instinct " if re.match(r"MI\d", row["name"]) else "AMD "
            add(first(gputables.AMD_NAME_RULES, prefix + row["name"]), row["name"])
    for row in official.get("therock_releases", []):
        add(first(gputables.AMD_NAME_RULES, row["product"]), row["product"])
    for name in ("radeon_win_compat", "radeon_linux_compat"):
        for row in official.get(name, []):
            for p in row["products"]:
                add(first(gputables.AMD_NAME_RULES, p), p)
    for key, desc in (official.get("pci_ids") or {}).get("devices", {}).items():
        lname = gpuwatch.lspci_name(key, desc)
        rules = gputables.AMD_NAME_RULES if key.startswith("1002") else gputables.INTEL_XPU_RULES
        add(first(rules, lname), f"{lname} ({key})")
        for r in gputables.PCI_DEVICE_RULES:
            if r.key == key:
                add(r, desc)
    for c in (official.get("intel_xpu") or {}).get("client", []):
        for h in c["hardware"]:
            add(first(gputables.INTEL_XPU_RULES, re.sub(r"\(CodeName: ([^)]*)\)", r"\1", h)), h)
    for d in (official.get("intel_xpu") or {}).get("datacenter", []):
        add(first(gputables.INTEL_XPU_RULES, d["device"]), d["device"])
    for row in official.get("nvidia", []):
        n = row["name"].rstrip("*")
        low = re.sub(r"\s+", " ", n.lower().replace("nvidia", "").replace("geforce", "")).strip()
        for r in gputables.NAME_CC_RULES:
            if re.search(r.key, low):
                add(r, n)
                break
    gfx_names: dict[str, list[str]] = {}
    for row in official.get("rocm_hw_specs", []):
        gfx_names.setdefault(row["gfx"], []).append(row.get("graphics_model") or row["name"])
    for row in official.get("therock_releases", []):
        gfx_names.setdefault(row["gfx"], []).append(row["product"])
    for r in gputables.AMD_ARCH_RULES:
        for n in gfx_names.get(r.key, []):
            add(r, n)
    return hits


# --- 判定 ------------------------------------------------------------------------------------------------


def amd_verdict(gfx: str, lang: str) -> str:
    j = 0 if lang == "en" else 1
    arch = hardware.AMD_ARCH.get(gfx, "?")
    if gfx in gputables.AMD_UNVERIFIED.values:
        return ("refused: not Release Ready in TheRock", "断る: TheRock で Release Ready でない")[j]
    if gfx in gputables.AMD_DISPLAY_ONLY.values:
        return ("refused: 2-CU display iGPU", "断る: 2 CU の画面用の内蔵 GPU")[j]
    if arch in gputables.AMD_LINUX_ONLY_ARCH:
        return ("used (Linux only)", "使う(Linux だけ)")[j]
    if arch not in gputables.AMD_SUPPORTED_ARCH:
        return (f"refused: {arch} (before RDNA 2)", f"断る: {arch}(RDNA 2 より前)")[j]
    where = (
        ("pytorch.org ROCm and TheRock", "pytorch.org の ROCm 版と TheRock")
        if gfx in gputables.PYTORCH_ROCM_LINUX.values
        else ("TheRock", "TheRock")
    )[j]
    return (f"used (Windows 11, Linux; {where})", f"使う(Windows 11・Linux。{where})")[j]


def intel_verdict(label: str, lang: str) -> str:
    if label in gputables.INTEL_LINUX_ONLY:
        return "used (Linux only)" if lang == "en" else "使う(Linux だけ)"
    return "used (Windows 11, Linux, WSL2)" if lang == "en" else "使う(Windows 11・Linux・WSL2)"


def cc_verdict(cc: tuple[int, int], lang: str) -> str:
    s = hardware.torch_support(cc, None, windows_driver=False)
    if not s.arch_builds and not s.usable:
        return "refused: no CUDA build" if lang == "en" else "断る: 対応する CUDA 版が無い"
    builds = ", ".join(s.arch_builds) if s.arch_builds else "-"
    return f"used ({builds})" if lang == "en" else f"使う({builds})"


def value_and_verdict(table: str, r: Rule, lang: str) -> tuple[str, str]:
    integ = t("integrated", lang)
    if table == "NAME_CC_RULES":
        return f"{r.value[0]}.{r.value[1]}", cc_verdict(r.value, lang)
    if table == "ARCH_MIN_DRIVER_RULES":
        return f"{r.value[0][0]} ({r.value[1]})", "-"
    if table == "AMD_ARCH_RULES":
        return r.value, amd_verdict(r.key, lang)
    if table == "AMD_NAME_RULES":
        gfx, inside = r.value
        return gfx + (f", {integ}" if inside else ""), amd_verdict(gfx, lang)
    if table == "AMD_CPU_IGPU_RULES":
        return f"{r.value}, {integ}", amd_verdict(r.value, lang)
    if table == "INTEL_XPU_RULES":
        label, inside, floor = r.value
        extra = [integ] if inside else []
        if floor:
            extra.append(f"VRAM ≥ {floor:g} GB")
        return label + (f" ({', '.join(extra)})" if extra else ""), intel_verdict(label, lang)
    if table == "PCI_DEVICE_RULES":
        ven = r.key.split(":")[0]
        if ven == "1002":
            g = hardware.amd_gfx(r.value)
            return f"{r.value} → {g[0] if g else '-'}", amd_verdict(g[0], lang) if g else "-"
        i = hardware.intel_xpu(f"intel {r.value}")
        return f"{r.value} → {i[0] if i else '-'}", intel_verdict(i[0], lang) if i else "-"
    return str(r.value), "-"


def names_cell(names: list[str], lang: str) -> str:
    if not names:
        return "-"
    shown = ", ".join(names[:MAX_NAMES])
    if len(names) > MAX_NAMES:
        shown += "; " + t("more", lang).format(n=len(names) - MAX_NAMES)
    return cell(shown)


def sources_cell(src: tuple[str, ...]) -> str:
    return ", ".join(code(s) for s in src)


def note_cell(r_note: tuple[str, str], lang: str) -> str:
    n = r_note[0 if lang == "ja" else 1]
    return f" ({cell(n)})" if n and lang == "en" else (f"({cell(n)})" if n else "")


# --- 書く ------------------------------------------------------------------------------------------------


def render(lang: str, official: dict) -> str:
    j = 0 if lang == "en" else 1
    other = OUT["ja" if lang == "en" else "en"].name
    switch = f"**English** · [日本語]({other})" if lang == "en" else f"[English]({other}) · **日本語**"
    pci = len((official.get("pci_ids") or {}).get("devices", {}))
    amd = len(official.get("rocm_hw_specs", [])) + len(official.get("therock_releases", []))
    nv = len(official.get("nvidia", []))
    hits = assign(official)
    out = [f"# {t('title', lang)}", "", switch, "", t("intro", lang), "", t("howto", lang), ""]
    out += [t("matched", lang).format(pci=pci, amd=amd, nv=nv), ""]

    tables = gputables.rules_by_table()
    out += [f"## {t('summary', lang)}", ""]
    head = (["Table", "Rows", "Rows with an official match"], ["表", "行", "公式の名前が当たる行"])[j]
    out += ["| " + " | ".join(head) + " |", "|---|---|---|"]
    for name, rules in tables.items():
        matched = sum(1 for r in rules if hits.get(id(r)))
        out.append(f"| {code(name)} | {len(rules)} | {matched} |")
    out.append("")

    for name, rules in tables.items():
        vendor, en, ja = TABLE_NAMES[name]
        out += [f"## {code(name)}", "", f"{vendor}: {en if lang == 'en' else ja}", ""]
        cols = t("cols", lang)
        out += ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
        for r in rules:
            value, verdict = value_and_verdict(name, r, lang)
            out.append(
                "| "
                + " | ".join(
                    [
                        vendor,
                        code(name),
                        code(r.key),
                        names_cell(hits.get(id(r), []), lang),
                        cell(value),
                        cell(verdict) + note_cell(r.note, lang),
                        sources_cell(r.source),
                        r.verified,
                        r.added or t("old", lang),
                    ]
                )
                + " |"
            )
        out.append("")

    out += [f"## {t('builds', lang)}", ""]
    head = (
        ["Build", "CUDA", "x86_64", "aarch64", "Min driver (Win / Linux)", "PyTorch", "Source", "Checked"],
        [
            "ビルド",
            "CUDA",
            "x86_64",
            "aarch64",
            "最低のドライバ(Win / Linux)",
            "PyTorch",
            "出典",
            "確かめた日",
        ],
    )[j]
    out += ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for b in gputables.TORCH_CUDA_BUILDS:
        ccs = {m: ", ".join(f"{c // 10}.{c % 10}" for c in sorted(v)) for m, v in b.ccs.items()}
        torch = b.torch if lang == "ja" else b.torch.replace("〜", " to ")
        out.append(
            f"| {b.tag} | {b.cuda} | {ccs.get('x86_64', '-')} | {ccs.get('aarch64', '-')} | "
            f"{b.min_driver_windows[0]} / {b.min_driver_linux[0]} | {cell(torch)}{note_cell(b.note, lang)} | "
            f"{sources_cell(b.source)} | {b.verified} |"
        )
    out.append("")

    out += [f"## {t('sets', lang)}", ""]
    head = (["Name", "Values", "Source", "Checked", "Note"], ["名前", "値", "出典", "確かめた日", "注意"])[j]
    out += ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for vs in gputables.value_sets():
        vals = sorted(vs.values) if isinstance(vs.values, frozenset) else list(vs.values)
        shown = ", ".join(str(v) for v in vals)
        note = vs.note[j] if vs.note[0] else "-"
        out.append(
            f"| {code(vs.name)} | {cell(shown)} | {sources_cell(vs.source)} | {vs.verified} | {cell(note)} |"
        )
    out.append("")

    out += [f"## {t('exceptions', lang)}", ""]
    for key, (ja_text, en_text) in sorted(gputables.KNOWN_EXCEPTIONS.items()):
        out.append(f"- {code(key)}: {en_text if lang == 'en' else ja_text}")
    out.append("")

    out += [f"## {t('sources', lang)}", ""]
    for sid, s in gputables.SOURCES.items():
        out.append(f"- `{sid}`: {cell(s.title)} — {s.url} ({s.read})")
    out.append("")
    return "\n".join(out)


def generate() -> dict[str, str]:
    official = gpuwatch.load_snapshot(OFFICIAL)
    return {lang: render(lang, official) for lang in OUT}


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true", help="書いてあるものと違えば 1 で終わる")
    args = p.parse_args(argv)
    texts = generate()
    bad = []
    for lang, path in OUT.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != texts[lang]:
                bad.append(str(path))
        else:
            path.write_text(texts[lang], encoding="utf-8", newline="\n")
    for b in bad:
        print(f"違う: {b}(python tools/gpu_inventory.py で作り直す)")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
